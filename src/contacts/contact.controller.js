import Contact from "./contact.model.js";
import nodemailer from "nodemailer";

export const submitContactForm = async (req, res) => {
  try {
    const { name, email, phone, subject, message } = req.body;

    if (!name || !email || !message) {
      return res.status(400).json({ message: "Please provide name, email and message." });
    }

    // 1. Save to Database
    const newContact = await Contact.create({
      name,
      email,
      phone,
      subject,
      message,
    });

    // 2. Send Email Notification
    const transporter = nodemailer.createTransport({
      host: "smtp.gmail.com",
      port: 587,
      secure: false, // Use TLS
      auth: {
        user: process.env.EMAIL_USER,
        pass: process.env.EMAIL_PASS,
      },
      tls: {
        rejectUnauthorized: false
      },
      connectionTimeout: 10000, // 10 seconds
    });

    const mailOptions = {
      from: `"Techland Contact" <${process.env.EMAIL_USER}>`,
      to: process.env.ADMIN_EMAIL || process.env.EMAIL_USER,
      subject: `New Inquiry: ${subject || "No Subject"} - from ${name}`,
      html: `
        <div style="font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif; max-width: 600px; margin: 0 auto; border: 1px solid #e0e0e0; border-radius: 12px; overflow: hidden; box-shadow: 0 4px 15px rgba(0,0,0,0.05);">
          <div style="background: linear-gradient(135deg, #163198 0%, #0d257a 100%); color: white; padding: 25px; text-align: center;">
            <h2 style="margin: 0; font-size: 24px; letter-spacing: 1px;">New Contact Inquiry</h2>
            <p style="margin: 5px 0 0 0; opacity: 0.8;">A new message has been received from your website.</p>
          </div>
          
          <div style="padding: 30px; background-color: #ffffff;">
            <table style="width: 100%; border-collapse: collapse;">
              <tr>
                <td style="padding: 10px 0; border-bottom: 1px solid #f0f0f0;">
                  <strong style="color: #163198; display: block; font-size: 12px; text-transform: uppercase;">Full Name</strong>
                  <span style="font-size: 16px; color: #333;">${name}</span>
                </td>
              </tr>
              <tr>
                <td style="padding: 10px 0; border-bottom: 1px solid #f0f0f0;">
                  <strong style="color: #163198; display: block; font-size: 12px; text-transform: uppercase;">Email Address</strong>
                  <span style="font-size: 16px; color: #333;">${email}</span>
                </td>
              </tr>
              <tr>
                <td style="padding: 10px 0; border-bottom: 1px solid #f0f0f0;">
                  <strong style="color: #163198; display: block; font-size: 12px; text-transform: uppercase;">Phone Number</strong>
                  <span style="font-size: 16px; color: #333;">${phone || "Not provided"}</span>
                </td>
              </tr>
              <tr>
                <td style="padding: 10px 0; border-bottom: 1px solid #f0f0f0;">
                  <strong style="color: #163198; display: block; font-size: 12px; text-transform: uppercase;">Subject</strong>
                  <span style="font-size: 16px; color: #333;">${subject || "General Inquiry"}</span>
                </td>
              </tr>
              <tr>
                <td style="padding: 20px 0 10px 0;">
                  <strong style="color: #163198; display: block; font-size: 12px; text-transform: uppercase; margin-bottom: 8px;">Message</strong>
                  <div style="background: #f9f9f9; padding: 15px; border-radius: 8px; border-left: 4px solid #163198; font-style: italic; color: #444;">
                    ${message}
                  </div>
                </td>
              </tr>
            </table>
          </div>
          
          <div style="background: #f4f6f9; padding: 15px; text-align: center; color: #888; font-size: 12px;">
            <p style="margin: 0;">This email was automatically generated by the Techland IT Solutions contact system.</p>
          </div>
        </div>
      `,
    };

    // Send email in the background so it doesn't block the response
    transporter.sendMail(mailOptions).catch(emailError => {
      console.error("Email sending failed in background:", emailError);
    });

    res.status(201).json({
      success: true,
      message: "Message received successfully!",
      contact: newContact
    });

  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

export const getContacts = async (req, res) => {
  try {
    const contacts = await Contact.find().sort({ createdAt: -1 });
    res.json(contacts);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

export const deleteContact = async (req, res) => {
  try {
    await Contact.findByIdAndDelete(req.params.id);
    res.json({ success: true, message: "Deleted" });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};
